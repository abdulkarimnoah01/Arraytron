"""Check that the documentation is current and consistent: python tools/check_docs.py   (plain Python, no Houdini needed)
Run it before every release and before handing the project to another person or another Claude instance. It fails (exit code 1) when:
 * the version named in README, STATUS, CLAUDE.md, docs/VERSIONING.md, docs/INDEX.md, docs/USER_GUIDE.md, HANDOFF.md differs from tools/versions.py CURRENT;
 * a file path written in backticks in the living documents (CLAUDE.md, HANDOFF.md, INDEX, USER_GUIDE, the top of README and STATUS) does not exist;
 * a relative Markdown link in those documents points nowhere;
 * a suite listed in CLAUDE.md is missing, or its '(N groups)' differs from the number of checks in the last validation result file;
 * a mutation name listed in CLAUDE.md does not appear in its suite;
 * a docs/*.md file is not listed in docs/INDEX.md; a required handoff section is missing."""
from pathlib import Path
import json, re, sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'tools'))
import versions
CUR=versions.CURRENT;problems=[]
def read(rel):
    p=ROOT/rel
    if not p.is_file():problems.append('missing document: '+rel);return ''
    return p.read_text(encoding='utf8')
def top(text,marker):
    i=text.find(marker);return text if i<0 else text[:i]
docs={'README.md':top(read('README.md'),'# Earlier releases'),'STATUS.md':top(read('STATUS.md'),'## Earlier:'),'CLAUDE.md':read('CLAUDE.md'),'HANDOFF.md':read('HANDOFF.md'),'docs/INDEX.md':read('docs/INDEX.md'),'docs/USER_GUIDE.md':read('docs/USER_GUIDE.md'),
      'docs/TROUBLESHOOTING.md':read('docs/TROUBLESHOOTING.md'),'docs/CACHING_AND_PIPELINE.md':read('docs/CACHING_AND_PIPELINE.md'),'INSTALL.md':read('INSTALL.md'),'CHANGELOG.md':read('CHANGELOG.md')}
# 1. version
for name in ('README.md','STATUS.md','CLAUDE.md','HANDOFF.md','docs/INDEX.md','docs/USER_GUIDE.md','INSTALL.md','CHANGELOG.md'):
    if CUR not in docs[name] and CUR[1:] not in docs[name]:problems.append('%s does not mention the current version %s'%(name,CUR))
if not re.search(r'Current release: \*\*%s\*\*'%re.escape(CUR),docs['CLAUDE.md']):problems.append('CLAUDE.md: "Current release: **%s**" missing'%CUR)
first=docs['STATUS.md'].splitlines()[0] if docs['STATUS.md'] else '';
if CUR not in first:problems.append('STATUS.md top heading is not %s: %r'%(CUR,first))
if not re.search(r'\*\*%s\*\* \(current\)'%re.escape(CUR),read('docs/VERSIONING.md')):problems.append('docs/VERSIONING.md does not mark %s as (current)'%CUR)
for name,pattern in (('docs/ROADMAP.md','Status 2026'),('docs/MASTER_PLAN_MAP.md','2026-')):
    text=read(name);last=[l for l in text.splitlines() if pattern in l][-1:] or ['']
    if CUR not in last[0]:problems.append('%s: the last status line does not mention %s'%(name,CUR))
# 2. paths
PATH=re.compile(r'`((?:tools|tests|src|docs|dist|icon|installer|release)/[A-Za-z0-9_.\-/]+?)`')
def exists(path):
    if any(c in path for c in '*<>'):return True
    if '..' in path or path.endswith('/'):return (ROOT/path.rstrip('/')).exists()
    return (ROOT/path).exists() or (ROOT/'dist/archive'/Path(path).name).exists() and path.startswith('dist/')
for name,text in docs.items():
    for m in PATH.finditer(text):
        p=m.group(1)
        if p.startswith(('release/','dist/backup')):continue                                                                                # generated by tools/make_release.py
        if p.startswith('dist/') and ('v0.' in p or '<' in p):continue                                                  # older releases are archived
        if not exists(p):problems.append('%s: path `%s` does not exist'%(name,p))
    for m in re.finditer(r'\]\(((?!http)[^)#\s]+)\)',text):
        link=m.group(1)
        base=ROOT/('docs' if name.startswith('docs/') else '')
        if not (ROOT/link).exists() and not (base/link).exists():problems.append('%s: link (%s) does not exist'%(name,link))
# 2b. the living documents must not point at another release's files (stale commands)
for name in ('CLAUDE.md','HANDOFF.md','INSTALL.md','docs/USER_GUIDE.md','docs/CACHING_AND_PIPELINE.md','docs/TROUBLESHOOTING.md'):
    for m in re.finditer(r'(?:dist/)?Arraytron_(v\d+\.\d+\.\d+)[^\s`]*',docs[name]):
        if m.group(1)!=CUR and 'archive' not in m.group(0):problems.append('%s mentions %s (current is %s)'%(name,m.group(0),CUR))
# 3. suites and group counts
claude=docs['CLAUDE.md']
for m in re.finditer(r'hython tests/(validate_\w+)\.py \S+\s+#[^\n]*?\((\d+) groups\)',claude):
    suite,count=m.group(1),int(m.group(2))
    if not (ROOT/'tests'/(suite+'.py')).is_file():problems.append('CLAUDE.md lists a missing suite '+suite);continue
    short=suite.replace('validate_','')
    result={'v016':'validation_%s.json'%CUR,'production':'production_%s.json'%CUR}.get(short,'validation_%s_%s.json'%(short,CUR))
    path=ROOT/'tests'/result
    if not path.is_file():problems.append('no result file tests/%s: run the suite'%result);continue
    n=len(json.loads(path.read_text(encoding='utf8'))['checks'])
    if n!=count:problems.append('CLAUDE.md says %s has %d groups, the last run has %d'%(suite,count,n))
for suite_file in sorted((ROOT/'tests').glob('validate_*.py')):
    if suite_file.stem not in claude and suite_file.stem not in ('validate_source','validate_renders','validate_rop','validate_line','validate_controls'):
        if not re.search(re.escape(suite_file.name),claude) and suite_file.stem.replace('validate_','') in ('physics','scatter','mask','overlap','grow','paint','fields','cluster','avoid','camera','polish','production','v016'):problems.append('CLAUDE.md does not list '+suite_file.name)
# 4. mutations named in CLAUDE.md exist in a suite
for m in re.finditer(r'`((?:[a-z_]+\|)+[a-z_]+)`',claude):
    for name in m.group(1).split('|'):
        if not any(name in f.read_text(encoding='utf8',errors='ignore') for f in (ROOT/'tests').glob('validate_*.py')):problems.append('mutation `%s` is listed in CLAUDE.md but no suite has it'%name)
# 5. every doc indexed, handoff sections
index=docs['docs/INDEX.md']
for md in sorted((ROOT/'docs').glob('*.md')):
    if md.name=='INDEX.md' or 'AUDIT' in md.name or md.name.startswith('TEAM_'):continue
    if md.name not in index:problems.append('docs/INDEX.md does not list '+md.name)
for heading in ('## 1. Read this first','## 2. State of the project','## 3. Environment on a new PC','## 4. How to continue','## 5. Rules and preferences','## 6. Open items','## 7. Memory for another Claude instance'):
    if heading not in docs['HANDOFF.md']:problems.append('HANDOFF.md misses the section "%s"'%heading)
for rel in ('handoff/claude_memory/MEMORY.md',):
    pass
print('check_docs: %d problem(s)'%len(problems))
for p in problems:print(' -',p)
sys.exit(1 if problems else 0)
